@dataclass
class MissionSimulationReport:
    """Structured result and audit record of an executed software mission simulation."""
    scenario_name: str
    status: str  # "verified", "completed", "failed", "timed_out", "incomplete", "partially_completed"
    termination_reason: str
    simulated_elapsed_time_s: float
    wall_clock_elapsed_time_s: float
    search_observations_count: int
    accepted_detections_count: int
    empty_observations_count: int
    total_survivors_found: int
    verified_deliveries_count: int
    failed_deliveries_count: int
    retried_tasks_count: int
    unresolved_tasks_count: int
    tasks: List[dict] = field(default_factory=list)
    final_drone_states: Dict[str, dict] = field(default_factory=dict)
    safety_alerts: List[dict] = field(default_factory=list)
    safety_incidents: List[dict] = field(default_factory=list)
    total_alert_notifications: int = 0
    comms_loss_events: List[dict] = field(default_factory=list)
    low_battery_events: List[dict] = field(default_factory=list)
    exceptions: List[dict] = field(default_factory=list)
    coverage_dependent_mode: bool = False
    coverage_rejected_observations_count: int = 0
    coverage_rejections: List[dict] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "scenario_name": self.scenario_name,
            "status": self.status,
            "termination_reason": self.termination_reason,
            "simulated_elapsed_time_s": self.simulated_elapsed_time_s,
            "wall_clock_elapsed_time_s": self.wall_clock_elapsed_time_s,
            "search_observations_count": self.search_observations_count,
            "accepted_detections_count": self.accepted_detections_count,
            "empty_observations_count": self.empty_observations_count,
            "total_survivors_found": self.total_survivors_found,
            "verified_deliveries_count": self.verified_deliveries_count,
            "failed_deliveries_count": self.failed_deliveries_count,
            "retried_tasks_count": self.retried_tasks_count,
            "unresolved_tasks_count": self.unresolved_tasks_count,
            "tasks": self.tasks,
            "final_drone_states": self.final_drone_states,
            "safety_alerts": self.safety_alerts,
            "safety_incidents": self.safety_incidents,
            "incident_count": len(self.safety_incidents),
            "total_alert_notifications": self.total_alert_notifications,
            "comms_loss_events": self.comms_loss_events,
            "exceptions": [
                {k: v for k, v in e.items() if k != "exception_instance"}
                for e in self.exceptions
            ],
            "coverage_dependent_mode": self.coverage_dependent_mode,
            "coverage_rejected_observations_count": self.coverage_rejected_observations_count,
            "coverage_rejections": self.coverage_rejections,
        }

    def to_json(self, indent: Optional[int] = None) -> str:
        """Serialize report to a valid JSON string."""
        return json.dumps(self.to_dict(), indent=indent)

    def format_summary(self) -> str:
        lines = [
            "=" * 78,
            f"  NIDAR RescueSwarm — Mission Simulation Summary: [{self.scenario_name.upper()}]",
            "  (Software-only simulation — no vehicle hardware or SITL physics)",
            "=" * 78,
            f"  Mission Status:          {self.status.upper()}",
            f"  Termination Reason:      {self.termination_reason}",
            f"  Simulated Elapsed Time:  {self.simulated_elapsed_time_s:.1f} s",
            f"  Wall-Clock Real Time:    {self.wall_clock_elapsed_time_s:.4f} s",
            "-" * 78,
            "  PERCEPTION & SEARCH METRICS:",
            f"    Search Observations:   {self.search_observations_count}",
            f"    Accepted Detections:   {self.accepted_detections_count}",
            f"    Empty Observations:    {self.empty_observations_count} (zero detections; no tasks fabricated)",
            f"    Total Survivors Found: {self.total_survivors_found}",
        ]
        if self.coverage_dependent_mode:
            lines.extend([
                f"    Coverage Mode:         ENABLED (Sensor footprint + sector bounds verified)",
                f"    Coverage Rejections:   {self.coverage_rejected_observations_count}",
            ])
        lines.extend([
            "-" * 78,
            "  DELIVERY & TASK OUTCOMES:",
            f"    Verified Deliveries:   {self.verified_deliveries_count}",
            f"    Failed Deliveries:     {self.failed_deliveries_count}",
            f"    Retried Tasks:         {self.retried_tasks_count}",
            f"    Unresolved Tasks:      {self.unresolved_tasks_count}",
        ])

        if self.tasks:
            lines.append("    Task Breakdown:")
            for t in self.tasks:
                retry_str = f" (Retry of {t['retry_of']})" if t.get("retry_of") else ""
                lines.append(
                    f"      - {t['task_id']}: Status={t['status'].upper()}{retry_str} | "
                    f"Assigned={t['assigned_drone_id']} | Conf={t['confidence']*100:.1f}% | "
                    f"DropOffset={t.get('drop_accuracy_offset_m', 0.0):.2f}m"
                )

        lines.extend([
            "-" * 78,
            "  FLEET DRONE FINAL STATES (6 Drones):",
        ])
        for d_id, st in sorted(self.final_drone_states.items()):
            active = f" | Task: {st['active_task']}" if st.get("active_task") else ""
            lines.append(
                f"    {d_id:<3} ({st['role'].upper():<8}): Status={st['status'].upper():<9} | "
                f"Battery={st['battery']*100:4.1f}%{active}"
            )

        lines.extend([
            "-" * 78,
            "  SAFETY WATCHDOG & INCIDENTS:",
            f"    Safety Incidents:      {len(self.safety_incidents)} (Unique lifecycle conditions)",
            f"    Alert Notifications:   {self.total_alert_notifications} (Total tick-level checks triggering action)",
            f"    Safety Alert Records:  {len(self.safety_alerts)} (Deduplicated alert entries)",
            f"    Comms Loss Events:     {len(self.comms_loss_events)}",
            f"    Exceptions Logged:     {len(self.exceptions)}",
        ])
        if self.safety_incidents:
            lines.append("    Active/Logged Incidents:")
            for inc in self.safety_incidents:
                res_str = f"Resolved@{inc['end_time']:.1f}s" if inc.get("resolved") else "ACTIVE"
                lines.append(
                    f"      - [{inc['incident_id']}] {inc['drone_id']:<3} | {inc['condition_type']:<18} | "
                    f"Level={inc['level'].upper():<9} | Action={inc['action'].upper():<14} | "
                    f"Ticks={inc['occurrence_count']:<3} | Status={res_str}"
                )
        lines.append("=" * 78)
        return "\n".join(lines)


