class SimulatedMissionRunner:
    """Repeatable, end-to-end discrete-time mission simulator integrating existing core modules."""

    def __init__(self, config: Optional[MissionScenarioConfig] = None) -> None:
        self.config = config or MissionScenarioConfig()
        validate_scenario_config(self.config)

    def run(self) -> Tuple[Dict[str, Any], MissionSimulationReport]:
        """Execute the deterministic mission simulation and return backward-compatible dict and report."""
        wall_start = time.perf_counter()
        cfg = self.config

        # 1. Initialize fleet models
        drones: List[Drone] = []
        for d_id in sorted(cfg.fleet_roles.keys()):
            role = cfg.fleet_roles[d_id]
            status = cfg.initial_statuses.get(d_id, DroneStatus.STANDBY if role == DroneRole.SEARCH else DroneStatus.READY)
            battery = cfg.initial_batteries.get(d_id, 1.0)
            drones.append(Drone(
                drone_id=d_id,
                role=role,
                status=status,
                battery_fraction=battery,
                position=cfg.base_location,
            ))

        # 2. Initialize SwarmManager with standard associator
        manager = SwarmManager(drones=drones)
        manager.mission_manager.transition_to(MissionState.INITIALIZING)
        manager.mission_manager.transition_to(MissionState.SEARCHING)

        # 3. Setup Camera & Coverage Plan
        camera = cfg.camera_calibration or CameraCalibration(
            image_width=1920,
            image_height=1080,
            hfov_deg=84.0,
            mount_pitch_deg=-90.0,
        )
        coverage_plan = plan_coverage(
            search_area=cfg.search_area,
            search_drone_ids=list(cfg.search_drone_ids),
            camera=camera,
            altitude_agl_m=cfg.altitude_agl_m,
            overlap_fraction=0.20,
            cruise_speed_mps=8.0,
        )

        # 4. Setup Safety Watchdog
        geofence_cfg = GeofenceConfig(
            boundary=cfg.geofence_boundary or cfg.search_area,
            min_altitude_agl_m=3.0,
            max_altitude_agl_m=cfg.altitude_agl_m + 30.0,
        )
        safety = SafetyManager(
            geofence=geofence_cfg,
            battery_config=BatteryFailsafeConfig(warning_fraction=0.30, rtl_fraction=0.20, land_critical_fraction=0.10),
            min_separation_m=5.0,
            heartbeat_timeout_s=5.0,
        )
        for d in drones:
            safety.record_heartbeat(d.drone_id, 0.0)

        delivery_profile = cfg.delivery_profile or DeliveryProfile(
            transit_altitude_m=25.0,
            release_altitude_m=8.0,
            horizontal_speed_mps=12.0,
            vertical_speed_mps=3.0,
            drop_tolerance_radius_m=3.0,
            release_hover_time_s=1.0,
            verification_time_s=1.5,
        )

        # Simulation state tracking
        sim_time = 0.0
        dt = cfg.dt_s
        active_controllers: Dict[str, DeliveryMissionController] = {}
        completed_controllers: Dict[str, DeliveryMissionController] = {}
        active_comms_loss_drones: Set[str] = set()
        pending_observations = sorted(cfg.observation_events, key=lambda e: e.timestamp_s)
        pending_low_batteries = sorted(cfg.low_battery_events, key=lambda e: e.timestamp_s)
        pending_comms_losses = sorted(cfg.comms_loss_events, key=lambda e: e.timestamp_s)
        pending_faults = sorted(cfg.drone_fault_events, key=lambda e: e.timestamp_s)

        captured_exceptions: List[dict] = []
        coverage_rejections: List[dict] = []
        coverage_rejected_obs_count = 0
        search_obs_count = 0
        accepted_det_count = 0
        empty_obs_count = 0
        loop_timed_out = False
        termination_reason = "Mission completed successfully"
        primary_controller: Optional[DeliveryMissionController] = None
        primary_task: Optional[RescueTask] = None

        # 5. Stepped Discrete Simulation Loop
        while sim_time < cfg.max_duration_s:
            # A. Process scheduled hardware fault events
            while pending_faults and pending_faults[0].timestamp_s <= sim_time:
                fev = pending_faults.pop(0)
                d = manager.get_drone(fev.drone_id)
                if d:
                    d.status = fev.status
                    if d.active_task_id and d.active_task_id in active_controllers:
                        ctrl = active_controllers.pop(d.active_task_id)
                        manager.update_task_status(d.active_task_id, TaskStatus.FAILED, drone_status=fev.status)
                        ctrl.abort()

            # B. Process scheduled low-battery events
            while pending_low_batteries and pending_low_batteries[0].timestamp_s <= sim_time:
                lbe = pending_low_batteries.pop(0)
                d = manager.get_drone(lbe.drone_id)
                if d:
                    d.battery_fraction = lbe.battery_fraction
                    telem = DroneTelemetry(d.drone_id, d.position or cfg.base_location, altitude_agl_m=cfg.altitude_agl_m, heading_deg=0.0)
                    safety.check_telemetry(telem, d.battery_fraction, sim_time)
                    if d.battery_fraction <= 0.20 and d.active_task_id in active_controllers:
                        ctrl = active_controllers.pop(d.active_task_id)
                        manager.update_task_status(d.active_task_id, TaskStatus.FAILED)
                        ctrl.abort()

            # C. Process scheduled comms-loss events
            while pending_comms_losses and pending_comms_losses[0].timestamp_s <= sim_time:
                cle = pending_comms_losses.pop(0)
                active_comms_loss_drones.add(cle.drone_id)

            # Record heartbeat for all connected fleet drones (standby at base or in flight)
            for d_id in cfg.fleet_roles.keys():
                if d_id not in active_comms_loss_drones:
                    safety.record_heartbeat(d_id, sim_time)

            # D. Update search drones (S1, S2, S3)
            search_telemetries: Dict[str, DroneTelemetry] = {}
            for s_id in cfg.search_drone_ids:
                s_drone = manager.get_drone(s_id)
                sector = coverage_plan.sectors[s_id]
                # Determine search drone simulated position along sector path
                wps = sector.waypoints
                wp_idx = min(len(wps) - 1, int(sim_time / 15.0) % len(wps))
                curr_pos = wps[wp_idx]
                s_drone.position = curr_pos
                s_telem = DroneTelemetry(s_id, curr_pos, altitude_agl_m=cfg.altitude_agl_m, heading_deg=0.0)
                search_telemetries[s_id] = s_telem

                if s_id not in active_comms_loss_drones:
                    safety.check_telemetry(s_telem, s_drone.battery_fraction, sim_time)

            # E. Process observation events scheduled for current time step
            while pending_observations and pending_observations[0].timestamp_s <= sim_time:
                obs = pending_observations.pop(0)
                search_obs_count += 1

                # If observing drone lost comms, observation is dropped
                if obs.drone_id in active_comms_loss_drones:
                    continue

                if not obs.detections:
                    # Empty detection observation — NEVER fabricate detections
                    empty_obs_count += 1
                    continue

                # Valid detections present
                drone_telem = obs.drone_telemetry or search_telemetries.get(obs.drone_id)
                if drone_telem is None:
                    drone_telem = DroneTelemetry(obs.drone_id, cfg.base_location, altitude_agl_m=cfg.altitude_agl_m, heading_deg=0.0)

                detections_with_geo = []
                for det in obs.detections:
                    try:
                        geo = estimate_survivor_location(det, drone_telem, camera)
                    except LocalizationError as exc:
                        if cfg.require_coverage_footprint:
                            coverage_rejected_obs_count += 1
                            coverage_rejections.append({
                                "sim_time": sim_time,
                                "drone_id": obs.drone_id,
                                "frame_id": obs.frame_id,
                                "reason": "LOCALIZATION_FAILURE",
                                "details": f"Target localization failed: {exc}",
                            })
                            continue
                        raise

                    # Coverage footprint & sector validation mode (if enabled)
                    if cfg.require_coverage_footprint:
                        # Check 0: Missing or non-finite coordinates
                        if geo.location is None or not (math.isfinite(geo.location.latitude) and math.isfinite(geo.location.longitude)):
                            coverage_rejected_obs_count += 1
                            coverage_rejections.append({
                                "sim_time": sim_time,
                                "drone_id": obs.drone_id,
                                "frame_id": obs.frame_id,
                                "reason": "INVALID_COORDINATES",
                                "details": "Survivor estimate contains non-finite or missing coordinates",
                            })
                            continue

                        sector = coverage_plan.sectors.get(obs.drone_id)
                        # Check 1: Sector boundary containment
                        if sector and not sector.area.contains(geo.location):
                            coverage_rejected_obs_count += 1
                            coverage_rejections.append({
                                "sim_time": sim_time,
                                "drone_id": obs.drone_id,
                                "frame_id": obs.frame_id,
                                "reason": "OUT_OF_ASSIGNED_SECTOR",
                                "details": f"Survivor position Lat {geo.location.latitude:.6f}, Lon {geo.location.longitude:.6f} outside assigned sector for {obs.drone_id}",
                            })
                            continue

                        # Check 2: Instantaneous sensor ground footprint radius
                        swath_w = compute_ground_swath_width(camera, cfg.altitude_agl_m)
                        footprint_radius_m = (swath_w / 2.0) * 1.10
                        ground_dist_m = haversine_distance_m(drone_telem.position, geo.location)
                        if ground_dist_m > footprint_radius_m:
                            coverage_rejected_obs_count += 1
                            coverage_rejections.append({
                                "sim_time": sim_time,
                                "drone_id": obs.drone_id,
                                "frame_id": obs.frame_id,
                                "reason": "OUT_OF_FOOTPRINT",
                                "details": f"Drone at Lat {drone_telem.position.latitude:.6f}, Lon {drone_telem.position.longitude:.6f} is {ground_dist_m:.1f}m from target (> {footprint_radius_m:.1f}m footprint radius)",
                            })
                            continue

                    detections_with_geo.append((det, geo))
                    accepted_det_count += 1

                if not detections_with_geo:
                    continue

                batch_results = manager.process_detections_batch(
                    detections_with_geo=detections_with_geo,
                    detected_by_drone_id=obs.drone_id,
                    frame_id=obs.frame_id,
                    timestamp=sim_time,
                    minimum_confidence=cfg.min_confidence,
                )
                if primary_task is None and batch_results:
                    primary_task = batch_results[0][0]

            # F. Dispatch eligible delivery drones to assigned tasks
            for r in list(manager.survivor_records.values()):
                t = r.task
                if t.status == TaskStatus.ASSIGNED and t.task_id not in active_controllers and t.task_id not in completed_controllers:
                    assigned_drone = manager.get_drone(t.assigned_drone_id)
                    if assigned_drone and assigned_drone.status not in (DroneStatus.FAULT, DroneStatus.OFFLINE):
                        outcome_spec = cfg.delivery_outcomes.get(t.task_id, cfg.delivery_outcomes.get("default", DeliveryOutcomeSpec()))
                        ctrl = DeliveryMissionController(
                            drone_id=t.assigned_drone_id,
                            task=t,
                            home_location=cfg.base_location,
                            profile=delivery_profile,
                            verification_method=outcome_spec.verification_method,
                        )
                        ctrl.start_mission()
                        manager.update_task_status(t.task_id, TaskStatus.EN_ROUTE)
                        active_controllers[t.task_id] = ctrl
                        if primary_controller is None:
                            primary_controller = ctrl

            # G. Step active delivery mission controllers
            flying_telemetries: Dict[str, DroneTelemetry] = dict(search_telemetries)
            for t_id, ctrl in list(active_controllers.items()):
                d_id = ctrl.drone_id
                d_drone = manager.get_drone(d_id)

                outcome_spec = cfg.delivery_outcomes.get(t_id, cfg.delivery_outcomes.get("default", DeliveryOutcomeSpec()))

                try:
                    if outcome_spec.outcome == "exception" and ctrl.state in (DeliveryState.EN_ROUTE, DeliveryState.APPROACH):
                        raise RuntimeError(outcome_spec.exception_message or "Simulated delivery actuator exception")

                    ctrl.update(dt)

                    # Intercept drop verification states
                    if ctrl.state == DeliveryState.VERIFY_DROP:
                        if outcome_spec.outcome == "fail_verification":
                            ctrl.delivery_verified = False
                            ctrl.verification_details = "Drop verification failed: sensor indicated kit release failure"
                            ctrl.state = DeliveryState.ASCENT
                        elif outcome_spec.outcome == "sensor_verified":
                            ctrl.confirm_ground_delivery(
                                source="ground_contact_sensor",
                                details=outcome_spec.verification_details or "Ground lanyard impact signal confirmed",
                            )
                        elif outcome_spec.outcome == "optical_verified":
                            ctrl.confirm_ground_delivery(
                                source="optical_confirmation",
                                details=outcome_spec.verification_details or "Downward camera confirmed payload on ground",
                            )
                        elif outcome_spec.outcome == "drop_failed":
                            ctrl.abort()

                    d_drone.position = ctrl.current_position
                    if ctrl.altitude_agl_m > 0.5:
                        d_telem = DroneTelemetry(d_id, ctrl.current_position, altitude_agl_m=ctrl.altitude_agl_m, heading_deg=0.0)
                        flying_telemetries[d_id] = d_telem
                        safety.check_telemetry(d_telem, d_drone.battery_fraction, sim_time)

                    # Check terminal state of controller
                    if ctrl.state == DeliveryState.COMPLETED:
                        if ctrl.delivery_verified:
                            manager.update_task_status(t_id, TaskStatus.VERIFIED)
                        else:
                            manager.update_task_status(t_id, TaskStatus.FAILED)
                        completed_controllers[t_id] = ctrl
                        del active_controllers[t_id]
                    elif ctrl.state == DeliveryState.ABORTED:
                        manager.update_task_status(t_id, TaskStatus.FAILED)
                        completed_controllers[t_id] = ctrl
                        del active_controllers[t_id]

                except Exception as exc:
                    captured_exceptions.append({
                        "task_id": t_id,
                        "drone_id": d_id,
                        "sim_time": sim_time,
                        "error_type": type(exc).__name__,
                        "error_msg": str(exc),
                        "trace": traceback.format_exc(),
                        "exception_instance": exc,
                    })
                    manager.update_task_status(t_id, TaskStatus.FAILED)
                    completed_controllers[t_id] = ctrl
                    del active_controllers[t_id]

            # H. Check fleet safety: proximity and telemetry timeouts
            safety.check_fleet_proximity(flying_telemetries, sim_time)
            timeout_alerts = safety.check_telemetry_timeouts(list(cfg.fleet_roles.keys()), sim_time)
            for alert in timeout_alerts:
                if alert.action == SafetyAction.RTL:
                    fault_drone = manager.get_drone(alert.drone_id)
                    if fault_drone and fault_drone.status not in (DroneStatus.FAULT, DroneStatus.OFFLINE):
                        if fault_drone.role == DroneRole.DELIVERY and fault_drone.active_task_id in active_controllers:
                            ctrl = active_controllers.pop(fault_drone.active_task_id)
                            manager.update_task_status(fault_drone.active_task_id, TaskStatus.FAILED, drone_available=False)
                            ctrl.abort()
                        elif fault_drone.role == DroneRole.SEARCH:
                            fault_drone.status = DroneStatus.RETURNING

            # I. Check mission lifecycle completion
            all_observations_done = len(pending_observations) == 0
            all_tasks = manager.get_all_tasks()
            all_tasks_settled = bool(all_tasks) and all(t.status in (TaskStatus.VERIFIED, TaskStatus.FAILED) for t in all_tasks)
            no_active_controllers = len(active_controllers) == 0

            if all_observations_done and (all_tasks_settled or not all_tasks) and no_active_controllers:
                if manager.mission_manager.state in (MissionState.SEARCHING, MissionState.RESCUE_IN_PROGRESS):
                    manager.mission_manager.transition_to(MissionState.RETURNING)
                manager.mission_manager.transition_to(MissionState.COMPLETED)
                termination_reason = "All search sectors swept and all rescue missions completed"
                sim_time += dt
                break

            sim_time += dt

        # 6. Post-loop termination & cleanup
        interrupted: List[str] = []
        if sim_time >= cfg.max_duration_s and manager.mission_manager.state != MissionState.COMPLETED:
            loop_timed_out = True
            timed_out_tasks = list(active_controllers.keys())
            pending_tasks = [t.task_id for t in manager.get_all_tasks() if t.status not in (TaskStatus.VERIFIED, TaskStatus.FAILED)]
            interrupted = sorted(set(timed_out_tasks + pending_tasks))
            if interrupted:
                termination_reason = f"Mission simulation timed out after {cfg.max_duration_s:.1f}s with unresolved task(s): {', '.join(interrupted)}"
            else:
                termination_reason = f"Mission simulation timed out after {cfg.max_duration_s:.1f}s"
            # Abort any in-flight delivery controllers
            for t_id, ctrl in list(active_controllers.items()):
                manager.update_task_status(t_id, TaskStatus.FAILED)
                ctrl.abort()
                completed_controllers[t_id] = ctrl
            active_controllers.clear()
            if manager.mission_manager.state in (MissionState.SEARCHING, MissionState.RESCUE_IN_PROGRESS):
                manager.mission_manager.transition_to(MissionState.RETURNING)
            manager.mission_manager.transition_to(MissionState.COMPLETED)

        wall_end = time.perf_counter()

        # 7. Compile Mission Report
        all_tasks = manager.get_all_tasks()
        verified_count = sum(1 for t in all_tasks if t.status == TaskStatus.VERIFIED)
        failed_count = sum(1 for t in all_tasks if t.status == TaskStatus.FAILED)
        retried_count = sum(1 for t in all_tasks if t.retry_of is not None)
        unresolved_count = sum(1 for t in all_tasks if t.status not in (TaskStatus.VERIFIED, TaskStatus.FAILED))
        if loop_timed_out and interrupted:
            unresolved_count = max(unresolved_count, len(interrupted))

        permanently_failed_tasks = [
            t for t in all_tasks
            if t.status == TaskStatus.FAILED
            and not any(r.retry_of == t.task_id and r.status == TaskStatus.VERIFIED for r in all_tasks)
        ]

        if captured_exceptions:
            overall_status = "failed"
            termination_reason = f"Mission aborted due to {len(captured_exceptions)} controller exception(s)"
        elif loop_timed_out:
            overall_status = "timed_out"
        elif unresolved_count > 0:
            overall_status = "incomplete"
            termination_reason = f"Mission ended with {unresolved_count} unresolved task(s)"
        elif permanently_failed_tasks and verified_count == 0:
            overall_status = "failed"
            termination_reason = f"All {len(all_tasks)} delivery task(s) failed"
        elif permanently_failed_tasks and verified_count > 0:
            overall_status = "partially_completed"
            termination_reason = f"Completed with {verified_count} verified and {len(permanently_failed_tasks)} permanently failed task(s)"
        elif verified_count > 0:
            overall_status = "verified"
        else:
            overall_status = "completed"

        task_records = []
        for t in all_tasks:
            ctrl = completed_controllers.get(t.task_id) or active_controllers.get(t.task_id)
            task_records.append({
                "task_id": t.task_id,
                "status": t.status.value,
                "assigned_drone_id": t.assigned_drone_id,
                "confidence": t.confidence,
                "retry_of": t.retry_of,
                "location": {"latitude": t.location.latitude, "longitude": t.location.longitude} if t.location else None,
                "drop_accuracy_offset_m": ctrl.drop_accuracy_offset_m if ctrl else 0.0,
                "verified": ctrl.delivery_verified if ctrl else False,
                "verification_method": ctrl.verification_method.value if ctrl else None,
            })

        drone_states = {
            d_id: {
                "role": d.role.value,
                "status": d.status.value,
                "battery": d.battery_fraction,
                "active_task": d.active_task_id,
            }
            for d_id, d in manager.drones.items()
        }

        alerts_record = [
            {
                "level": a.level.value,
                "action": a.action.value,
                "drone_id": a.drone_id,
                "message": a.message,
                "timestamp": a.timestamp,
            }
            for a in safety.alert_history
        ]

        report = MissionSimulationReport(
            scenario_name=cfg.name,
            status=overall_status,
            termination_reason=termination_reason,
            simulated_elapsed_time_s=min(sim_time, cfg.max_duration_s),
            wall_clock_elapsed_time_s=wall_end - wall_start,
            search_observations_count=search_obs_count,
            accepted_detections_count=accepted_det_count,
            empty_observations_count=empty_obs_count,
            total_survivors_found=len(all_tasks),
            verified_deliveries_count=verified_count,
            failed_deliveries_count=failed_count,
            retried_tasks_count=retried_count,
            unresolved_tasks_count=unresolved_count,
            tasks=task_records,
            final_drone_states=drone_states,
            safety_alerts=alerts_record,
            safety_incidents=[inc.to_dict() for inc in safety.get_all_incidents()],
            total_alert_notifications=safety.total_alerts_evaluated,
            comms_loss_events=[{"timestamp_s": e.timestamp_s, "drone_id": e.drone_id} for e in cfg.comms_loss_events],
            low_battery_events=[{"timestamp_s": e.timestamp_s, "drone_id": e.drone_id, "battery": e.battery_fraction} for e in cfg.low_battery_events],
            exceptions=captured_exceptions,
            coverage_dependent_mode=cfg.require_coverage_footprint,
            coverage_rejected_observations_count=coverage_rejected_obs_count,
            coverage_rejections=coverage_rejections,
        )

        # Backward compatible dict matching run_full_mission_simulation()
        last_error = None
        if captured_exceptions:
            last_error = captured_exceptions[-1].get("exception_instance") or RuntimeError(captured_exceptions[-1]["error_msg"])

        compat_result = {
            "status": overall_status,
            "manager": manager,
            "task": primary_task or (all_tasks[0] if all_tasks else None),
            "controller": primary_controller or (list(completed_controllers.values())[0] if completed_controllers else None),
            "error": last_error,
            "timed_out": loop_timed_out,
            "summary": manager.get_fleet_summary(),
            "report": report,
        }

        return compat_result, report


