@dataclass
class ObservationEvent:
    """Scenario-driven visual observation event generated by a search drone."""
    timestamp_s: float
    drone_id: str
    frame_id: str
    detections: List[Detection] = field(default_factory=list)
    drone_telemetry: Optional[DroneTelemetry] = None
    is_known_distinct: bool = False
    notes: Optional[str] = None

    def __post_init__(self) -> None:
        if self.timestamp_s < 0.0:
            raise ValueError(f"Observation timestamp must be non-negative, got {self.timestamp_s}")
        if not self.drone_id:
            raise ValueError("Observation drone_id cannot be empty")
        if not self.frame_id:
            raise ValueError("Observation frame_id cannot be empty")


@dataclass
class DeliveryOutcomeSpec:
    """Outcome behavior configuration for a simulated delivery mission."""
    outcome: str = "verified"  # "verified", "fail_verification", "drop_failed", "timeout", "exception"
    verification_method: DeliveryVerificationMethod = DeliveryVerificationMethod.SIMULATED_TIMER
    exception_message: Optional[str] = None
    verification_details: Optional[str] = None
    drop_accuracy_offset_m: float = 0.0


@dataclass
class CommsLossEvent:
    """Simulated telemetry loss event triggering watchdog timeout."""
    timestamp_s: float
    drone_id: str
    duration_s: Optional[float] = None  # None indicates permanent loss for remainder of mission

    def __post_init__(self) -> None:
        if self.timestamp_s < 0.0:
            raise ValueError(f"CommsLossEvent timestamp must be non-negative, got {self.timestamp_s}")
        if not self.drone_id:
            raise ValueError("CommsLossEvent drone_id cannot be empty")


@dataclass
class LowBatteryEvent:
    """Simulated battery drain event triggering battery failsafes."""
    timestamp_s: float
    drone_id: str
    battery_fraction: float

    def __post_init__(self) -> None:
        if self.timestamp_s < 0.0:
            raise ValueError(f"LowBatteryEvent timestamp must be non-negative, got {self.timestamp_s}")
        if not self.drone_id:
            raise ValueError("LowBatteryEvent drone_id cannot be empty")
        if not (0.0 <= self.battery_fraction <= 1.0):
            raise ValueError(f"battery_fraction must be in [0.0, 1.0], got {self.battery_fraction}")


@dataclass
class DroneFaultEvent:
    """Simulated hardware fault event transitioning drone to FAULT or OFFLINE."""
    timestamp_s: float
    drone_id: str
    status: DroneStatus = DroneStatus.FAULT
    reason: str = "Hardware fault"

    def __post_init__(self) -> None:
        if self.timestamp_s < 0.0:
            raise ValueError(f"DroneFaultEvent timestamp must be non-negative, got {self.timestamp_s}")
        if not self.drone_id:
            raise ValueError("DroneFaultEvent drone_id cannot be empty")
        if self.status not in (DroneStatus.FAULT, DroneStatus.OFFLINE):
            raise ValueError("DroneFaultEvent status must be FAULT or OFFLINE")


@dataclass
class MissionScenarioConfig:
    """Deterministic configuration defining an end-to-end 6-drone mission scenario."""
    name: str = "nominal"
    description: str = "Deterministic 6-drone mission scenario"
    search_drone_ids: List[str] = field(default_factory=lambda: ["S1", "S2", "S3"])
    delivery_drone_ids: List[str] = field(default_factory=lambda: ["D1", "D2", "D3"])
    fleet_roles: Dict[str, DroneRole] = field(default_factory=lambda: {
        "S1": DroneRole.SEARCH, "S2": DroneRole.SEARCH, "S3": DroneRole.SEARCH,
        "D1": DroneRole.DELIVERY, "D2": DroneRole.DELIVERY, "D3": DroneRole.DELIVERY,
    })
    initial_batteries: Dict[str, float] = field(default_factory=lambda: {
        "S1": 1.0, "S2": 1.0, "S3": 1.0,
        "D1": 0.85, "D2": 0.94, "D3": 0.78,
    })
    initial_statuses: Dict[str, DroneStatus] = field(default_factory=lambda: {
        "S1": DroneStatus.STANDBY, "S2": DroneStatus.STANDBY, "S3": DroneStatus.STANDBY,
        "D1": DroneStatus.READY, "D2": DroneStatus.READY, "D3": DroneStatus.READY,
    })
    base_location: GeoPoint = field(default_factory=lambda: GeoPoint(latitude=12.9710, longitude=77.5935, altitude_m=0.0))
    search_area: SearchArea = field(default_factory=lambda: SearchArea(min_lat=12.9712, min_lon=77.5940, max_lat=12.9736, max_lon=77.5976))
    geofence_boundary: Optional[SearchArea] = field(default_factory=lambda: SearchArea(min_lat=12.9700, min_lon=77.5920, max_lat=12.9750, max_lon=77.5990))
    altitude_agl_m: float = 30.0
    camera_calibration: Optional[CameraCalibration] = None
    delivery_profile: Optional[DeliveryProfile] = None
    max_duration_s: float = 600.0
    dt_s: float = 1.0
    seed: Optional[int] = 42
    observation_events: List[ObservationEvent] = field(default_factory=list)
    delivery_outcomes: Dict[str, DeliveryOutcomeSpec] = field(default_factory=dict)
    comms_loss_events: List[CommsLossEvent] = field(default_factory=list)
    low_battery_events: List[LowBatteryEvent] = field(default_factory=list)
    drone_fault_events: List[DroneFaultEvent] = field(default_factory=list)
    min_confidence: float = 0.25
    require_coverage_footprint: bool = False


def validate_scenario_config(config: MissionScenarioConfig) -> None:
    """Validate all scenario configuration parameters and reject invalid values with clear errors."""
    if not isinstance(config, MissionScenarioConfig):
        raise ValueError(f"Expected MissionScenarioConfig, got {type(config)}")

    # 1. Fleet validation: exactly 6 drones, S1-S3 SEARCH, D1-D3 DELIVERY
    all_drones = set(config.search_drone_ids) | set(config.delivery_drone_ids)
    if len(all_drones) != 6:
        raise ValueError(f"Scenario fleet must contain exactly 6 unique drones, found {len(all_drones)}: {all_drones}")

    expected_search = {"S1", "S2", "S3"}
    expected_delivery = {"D1", "D2", "D3"}
    if set(config.search_drone_ids) != expected_search:
        raise ValueError(f"Search fleet must be exactly {expected_search}, got {set(config.search_drone_ids)}")
    if set(config.delivery_drone_ids) != expected_delivery:
        raise ValueError(f"Delivery fleet must be exactly {expected_delivery}, got {set(config.delivery_drone_ids)}")

    # Check roles
    for d_id in config.search_drone_ids:
        role = config.fleet_roles.get(d_id)
        if role != DroneRole.SEARCH:
            raise ValueError(f"Drone {d_id} must have role SEARCH, got {role}")
    for d_id in config.delivery_drone_ids:
        role = config.fleet_roles.get(d_id)
        if role != DroneRole.DELIVERY:
            raise ValueError(f"Drone {d_id} must have role DELIVERY, got {role}")

    # 2. Battery validation
    for d_id in all_drones:
        bat = config.initial_batteries.get(d_id, 1.0)
        if not (0.0 <= bat <= 1.0):
            raise ValueError(f"Initial battery for {d_id} must be in [0.0, 1.0], got {bat}")

    # 3. Geographic bounds
    if config.search_area is None:
        raise ValueError("search_area cannot be None")
    if not (config.search_area.min_lat < config.search_area.max_lat):
        raise ValueError("search_area min_lat must be strictly less than max_lat")
    if not (config.search_area.min_lon < config.search_area.max_lon):
        raise ValueError("search_area min_lon must be strictly less than max_lon")

    if config.base_location is None:
        raise ValueError("base_location cannot be None")

    # 4. Simulation timing
    if config.max_duration_s <= 0.0:
        raise ValueError(f"max_duration_s must be strictly positive, got {config.max_duration_s}")
    if config.dt_s <= 0.0:
        raise ValueError(f"dt_s must be strictly positive, got {config.dt_s}")
    if config.dt_s > config.max_duration_s:
        raise ValueError(f"dt_s ({config.dt_s}) cannot be greater than max_duration_s ({config.max_duration_s})")

    # 5. Observation events
    for idx, obs in enumerate(config.observation_events):
        if obs.drone_id not in config.search_drone_ids:
            raise ValueError(f"ObservationEvent #{idx} drone_id {obs.drone_id} is not an authorized search drone")
        if obs.timestamp_s < 0.0:
            raise ValueError(f"ObservationEvent #{idx} timestamp must be non-negative")
        for d_idx, det in enumerate(obs.detections):
            if not isinstance(det, Detection):
                raise ValueError(f"ObservationEvent #{idx} detection #{d_idx} is not a Detection instance")
            if not (0.0 <= det.confidence <= 1.0):
                raise ValueError(f"Detection confidence must be in [0.0, 1.0], got {det.confidence}")

    # 6. Low battery and comms loss events
    for idx, ev in enumerate(config.low_battery_events):
        if ev.drone_id not in all_drones:
            raise ValueError(f"LowBatteryEvent #{idx} drone_id {ev.drone_id} not in fleet")
        if not (0.0 <= ev.battery_fraction <= 1.0):
            raise ValueError(f"LowBatteryEvent #{idx} battery_fraction must be in [0.0, 1.0]")

    for idx, ev in enumerate(config.comms_loss_events):
        if ev.drone_id not in all_drones:
            raise ValueError(f"CommsLossEvent #{idx} drone_id {ev.drone_id} not in fleet")


