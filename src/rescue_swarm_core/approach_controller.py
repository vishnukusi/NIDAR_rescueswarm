"""Search-drone person detection, visual servoing approach, and hover controller.

Integrates the visual servoing and proportional translation control logic developed in
docs/Drone_project (drone_visual_servo.py / coor.py / closed_loop_test.py) into the
RescueSwarm core architecture for S1, S2, and S3.
"""

from dataclasses import dataclass, field
from enum import Enum
import math
import time
from typing import List, Optional, Tuple

from .localization import CameraCalibration, GeoPoint
from .perception import BoundingBox, Detection
from .safety_manager import SafetyAction


class ApproachState(str, Enum):
    """Lifecycle states for a search drone detecting, approaching, and inspecting a person."""
    SEARCH_PATROL = "search_patrol"        # Executing assigned coverage search waypoints
    TARGET_ACQUIRED = "target_acquired"    # Person/pedestrian detected by perception model
    APPROACHING = "approaching"            # Visual servoing: translating vehicle toward target center
    HOVERING = "hovering"                  # Target centered within deadband; hovering directly overhead
    TARGET_LOST = "target_lost"            # Target temporarily lost; holding and waiting for re-acquisition
    SEARCH_RESUMED = "search_resumed"      # Resuming search coverage after target loss or inspection
    SAFETY_OVERRIDE = "safety_override"    # Failsafe commanded (HOLD, RTL, EMERGENCY_LAND)


@dataclass
class TargetTrackingEstimate:
    """Estimated ground person / upper-body position in image space."""
    x1: int
    y1: int
    x2: int
    y2: int
    box_center_x: int
    box_center_y: int
    head_x: int
    head_y: int
    smooth_x: float
    smooth_y: float
    confidence: float
    class_name: str
    timestamp: float = field(default_factory=time.time)


@dataclass
class VisualServoCommand:
    """Command generated by the visual servoing approach controller."""
    error_x: float
    error_y: float
    body_forward_mps: float
    body_right_mps: float
    local_ned_north_mps: float
    local_ned_east_mps: float
    action_label: str
    is_centered: bool
    hold_yaw_rad: float


@dataclass
class ApproachControllerConfig:
    """Configurable parameters for proportional visual servoing."""
    kp_forward: float = 0.008
    kp_right: float = 0.008
    max_speed_mps: float = 1.0
    deadband_x_px: int = 35
    deadband_y_px: int = 35
    head_position_ratio: float = 0.12
    smoothing_factor: float = 0.30
    target_loss_timeout_s: float = 3.0
    required_hover_duration_s: float = 5.0


class SearchDroneApproachController:
    """Controls individual search drones (S1, S2, S3) transitioning from search to hover."""

    def __init__(
        self,
        drone_id: str,
        camera: Optional[CameraCalibration] = None,
        config: Optional[ApproachControllerConfig] = None,
    ) -> None:
        self.drone_id = drone_id
        self.camera = camera or CameraCalibration()
        self.config = config or ApproachControllerConfig()

        self.state = ApproachState.SEARCH_PATROL
        self.target_estimate: Optional[TargetTrackingEstimate] = None
        self.smooth_x: Optional[float] = None
        self.smooth_y: Optional[float] = None

        self._last_detection_time: float = 0.0
        self._hover_start_time: Optional[float] = None
        self._hover_duration_s: float = 0.0
        self._active_target_id: Optional[str] = None
        self._waypoint_paused: bool = False
        self._safety_override_action: Optional[SafetyAction] = None

    @property
    def is_waypoint_execution_paused(self) -> bool:
        """Indicates to coverage planner whether waypoint execution should be suspended."""
        return self._waypoint_paused

    def apply_safety_override(self, action: SafetyAction) -> None:
        """Immediately override controller behavior with safety failsafe command."""
        self._safety_override_action = action
        self.state = ApproachState.SAFETY_OVERRIDE

    def clear_safety_override(self) -> None:
        """Clear safety failsafe override and return to search patrol."""
        self._safety_override_action = None
        self.state = ApproachState.SEARCH_PATROL

    def update(
        self,
        detection: Optional[Detection],
        current_yaw_rad: float,
        dt_s: float = 0.1,
        current_time: Optional[float] = None,
    ) -> Tuple[ApproachState, VisualServoCommand]:
        """Step visual servoing controller on a new camera frame or detection observation.

        Args:
            detection: Detection from perception model or None if no target in frame.
            current_yaw_rad: Current vehicle heading in radians.
            dt_s: Time step in seconds.
            current_time: Timestamp for simulation timing.

        Returns:
            Tuple of (current_state, visual_servo_command)
        """
        now = current_time if current_time is not None else time.time()

        # Handle active safety failsafe override
        if self._safety_override_action in (SafetyAction.RTL, SafetyAction.HOLD, SafetyAction.EMERGENCY_LAND):
            self.state = ApproachState.SAFETY_OVERRIDE
            cmd = VisualServoCommand(
                error_x=0.0,
                error_y=0.0,
                body_forward_mps=0.0,
                body_right_mps=0.0,
                local_ned_north_mps=0.0,
                local_ned_east_mps=0.0,
                action_label="SAFETY OVERRIDE (" + self._safety_override_action.value.upper() + ")",
                is_centered=False,
                hold_yaw_rad=current_yaw_rad,
            )
            return self.state, cmd

        # Case 1: Target Detected in Frame
        if detection is not None and detection.class_name.lower() in ("pedestrian", "people", "person", "survivor"):
            self._last_detection_time = now
            self._waypoint_paused = True  # Suspend lawnmower waypoints

            img_w = self.camera.image_width
            img_h = self.camera.image_height
            cam_center_x = img_w // 2
            cam_center_y = img_h // 2

            # Convert normalized bbox to absolute pixels
            x1 = int(detection.bbox.xmin * img_w)
            y1 = int(detection.bbox.ymin * img_h)
            x2 = int(detection.bbox.xmax * img_w)
            y2 = int(detection.bbox.ymax * img_h)

            box_cx = (x1 + x2) // 2
            box_cy = (y1 + y2) // 2

            # Upper-body / head estimation (reusing existing tested ratio from Drone_project)
            head_x = box_cx
            head_y = y1 + int((y2 - y1) * self.config.head_position_ratio)

            # Exponential Moving Average Smoothing
            if self.smooth_x is None:
                self.smooth_x = float(head_x)
                self.smooth_y = float(head_y)
            else:
                alpha = self.config.smoothing_factor
                self.smooth_x = alpha * float(head_x) + (1.0 - alpha) * self.smooth_x
                self.smooth_y = alpha * float(head_y) + (1.0 - alpha) * self.smooth_y

            self.target_estimate = TargetTrackingEstimate(
                x1=x1,
                y1=y1,
                x2=x2,
                y2=y2,
                box_center_x=box_cx,
                box_center_y=box_cy,
                head_x=head_x,
                head_y=head_y,
                smooth_x=self.smooth_x,
                smooth_y=self.smooth_y,
                confidence=detection.confidence,
                class_name=detection.class_name,
                timestamp=now,
            )

            # Calculate Image Error from Camera Optical Center
            error_x = self.smooth_x - cam_center_x
            error_y = self.smooth_y - cam_center_y

            # Proportional Controller with Deadband
            is_centered_x = abs(error_x) <= self.config.deadband_x_px
            is_centered_y = abs(error_y) <= self.config.deadband_y_px
            is_centered = is_centered_x and is_centered_y

            right_vel = 0.0 if is_centered_x else (self.config.kp_right * error_x)
            forward_vel = 0.0 if is_centered_y else (-self.config.kp_forward * error_y)

            # Clamp velocities to MAX_SPEED
            max_s = self.config.max_speed_mps
            right_vel = max(-max_s, min(max_s, right_vel))
            forward_vel = max(-max_s, min(max_s, forward_vel))

            # Rotate Body Velocities into Local NED Frame (Yaw-lock translation)
            north_vel = forward_vel * math.cos(current_yaw_rad) - right_vel * math.sin(current_yaw_rad)
            east_vel = forward_vel * math.sin(current_yaw_rad) + right_vel * math.cos(current_yaw_rad)

            # State Transition & Action Labeling
            if is_centered:
                self.state = ApproachState.HOVERING
                if self._hover_start_time is None:
                    self._hover_start_time = now
                self._hover_duration_s = now - self._hover_start_time
                action_label = "HOLD POSITION (HOVERING)"
            else:
                self.state = ApproachState.APPROACHING
                self._hover_start_time = None
                self._hover_duration_s = 0.0
                actions = []
                if forward_vel > 0.05: actions.append("FORWARD")
                elif forward_vel < -0.05: actions.append("BACKWARD")
                if right_vel > 0.05: actions.append("RIGHT")
                elif right_vel < -0.05: actions.append("LEFT")
                action_label = " + ".join(actions) if actions else "STABILIZING"

            cmd = VisualServoCommand(
                error_x=error_x,
                error_y=error_y,
                body_forward_mps=forward_vel,
                body_right_mps=right_vel,
                local_ned_north_mps=north_vel,
                local_ned_east_mps=east_vel,
                action_label=action_label,
                is_centered=is_centered,
                hold_yaw_rad=current_yaw_rad,
            )
            return self.state, cmd

        # Case 2: No Target in Frame
        if self.state in (ApproachState.APPROACHING, ApproachState.HOVERING, ApproachState.TARGET_LOST):
            # Target temporarily lost
            silence = now - self._last_detection_time
            if silence <= self.config.target_loss_timeout_s:
                self.state = ApproachState.TARGET_LOST
                action_label = f"TARGET LOST (HOLDING {silence:.1f}s / {self.config.target_loss_timeout_s:.1f}s)"
            else:
                # Timed out -> Resume search patrol
                self.state = ApproachState.SEARCH_RESUMED
                self._waypoint_paused = False
                self.smooth_x = None
                self.smooth_y = None
                self._hover_start_time = None
                action_label = "RESUMING SEARCH PATROL"
        else:
            self.state = ApproachState.SEARCH_PATROL
            self._waypoint_paused = False
            action_label = "SEARCH PATROL (WAYPOINT FOLLOWING)"

        cmd = VisualServoCommand(
            error_x=0.0,
            error_y=0.0,
            body_forward_mps=0.0,
            body_right_mps=0.0,
            local_ned_north_mps=0.0,
            local_ned_east_mps=0.0,
            action_label=action_label,
            is_centered=False,
            hold_yaw_rad=current_yaw_rad,
        )
        return self.state, cmd

    def complete_inspection(self) -> None:
        """Signal that inspection and geolocation are complete, allowing search drone to resume patrol."""
        self.state = ApproachState.SEARCH_RESUMED
        self._waypoint_paused = False
        self.smooth_x = None
        self.smooth_y = None
        self._hover_start_time = None

    def reset(self) -> None:
        """Reset approach controller state."""
        self.state = ApproachState.SEARCH_PATROL
        self.target_estimate = None
        self.smooth_x = None
        self.smooth_y = None
        self._last_detection_time = 0.0
        self._hover_start_time = None
        self._hover_duration_s = 0.0
        self._waypoint_paused = False
        self._safety_override_action = None
